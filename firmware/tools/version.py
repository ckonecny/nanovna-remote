# Writes src/version.h with the firmware version: the git tag (v1.1.0), or tag-commits-hash for builds between tags,
# or "dev" without git. Runs before every build; the file is only rewritten when the version changed.
Import("env")  # noqa: F821
import subprocess
from pathlib import Path

project = Path(env["PROJECT_DIR"])  # noqa: F821
try:
    version = subprocess.run(["git", "describe", "--tags", "--always", "--dirty"], cwd=project, capture_output=True, text=True,
                             check=True).stdout.strip() or "dev"
except Exception:
    version = "dev"
dst = project / "src" / "version.h"
text = f'// generated by tools/version.py - do not edit\n#pragma once\n#define FW_VERSION "{version}"\n'
if not dst.exists() or dst.read_text() != text:
    dst.write_text(text)
